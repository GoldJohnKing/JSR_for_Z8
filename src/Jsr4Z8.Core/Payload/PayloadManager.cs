using System.Security.Cryptography;

namespace Jsr4Z8.Core.Payload;

/// <summary>
/// Extracts the embedded backend payload to disk and keeps it verifiably intact.
/// Target: %LOCALAPPDATA%\JSR4Z8\backend\&lt;manifest hash first 16 hex chars&gt;\ — a
/// directory containing "Jiangtherapee Bridge.exe" + the full resources/ tree.
/// Behavior:
///  - Existing target whose every manifest entry matches its SHA-256 → returned directly
///    (<see cref="ManifestVerifyPasses"/> counts these full passes; once verified, later
///    calls in the same instance hit a session cache and do not touch disk at all).
///  - Any missing file / hash mismatch / leftover ".incomplete" marker → the ENTIRE target
///    directory is deleted and fully re-extracted (self-heal).
///  - Extraction is atomic: files are written into a sibling "&lt;hash&gt;.tmp-&lt;pid&gt;"
///    directory behind a ".incomplete" marker, hash-verified as they are written
///    (streaming SHA-256 while decompressing), then the marker is removed and the
///    directory is renamed to its final name. Renames and cleanup-directory deletes
///    retry on transient IOException/UnauthorizedAccessException — on Windows, AV
///    scanners and the search indexer briefly lock freshly-written directories.
///    A crash can therefore never leave a
///    half-written target; crashed ".tmp-*" siblings are cleaned up on the next run.
/// </summary>
public sealed class PayloadManager
{
    public const string PayloadResourceName = "Jsr4Z8.Core.Payload.Embedded.payload.bin";
    public const string ManifestResourceName = "Jsr4Z8.Core.Payload.Embedded.payload.manifest.json";
    public const string IncompleteMarkerName = ".incomplete";

    /// <summary>Production backend root base: %LOCALAPPDATA%\JSR4Z8\backend.</summary>
    public static readonly string DefaultBackendRoot = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
        "JSR4Z8", "backend");

    private const int HashDirLength = 16;

    /// <summary>Attempts for rename/cleanup-delete before giving up: AV scanners and the
    /// Windows search indexer briefly lock freshly-written directories, surfacing as a
    /// transient <see cref="IOException"/> or <see cref="UnauthorizedAccessException"/>.</summary>
    internal const int FsLockRetryAttempts = 5;

    /// <summary>Backoff between rename/cleanup-delete attempts, in milliseconds.</summary>
    internal const int FsLockRetryBackoffMs = 200;

    private readonly string _backendRoot;
    private readonly Func<Stream> _openPayload;
    private readonly Func<PayloadManifest> _loadManifest;
    private string? _verifiedDir;

    /// <summary>
    /// Production instance reading the release payload from the assembly's embedded
    /// resources (generated by tools/pack-payload and embedded at release build time).
    /// </summary>
    public PayloadManager() : this(
        DefaultBackendRoot,
        static () => typeof(PayloadManager).Assembly.GetManifestResourceStream(PayloadResourceName)
            ?? throw new InvalidOperationException($"缺少嵌入资源 {PayloadResourceName}（发布构建由 tools/pack-payload 生成并嵌入）"),
        static () =>
        {
            using Stream stream = typeof(PayloadManager).Assembly.GetManifestResourceStream(ManifestResourceName)
                ?? throw new InvalidOperationException($"缺少嵌入资源 {ManifestResourceName}（发布构建由 tools/pack-payload 生成并嵌入）");
            return PayloadPacker.ReadManifestJson(stream);
        })
    {
    }

    /// <summary>Test/DI instance: backend root base, payload stream opener and manifest loader supplied by the caller.</summary>
    internal PayloadManager(string backendRoot, Func<Stream> openPayload, Func<PayloadManifest> loadManifest)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(backendRoot);
        _backendRoot = backendRoot;
        _openPayload = openPayload;
        _loadManifest = loadManifest;
    }

    /// <summary>
    /// Test hook: how many full manifest re-hash validations ran against an existing
    /// extracted directory. The session fast-path must not increment it.
    /// </summary>
    internal int ManifestVerifyPasses { get; private set; }

    /// <summary>
    /// Test hook: replaces the tmp→final directory rename (production: <see cref="Directory.Move"/>)
    /// so tests can inject transient lock failures and assert the retry path. Receives
    /// (source, target) and must perform or fail the move itself.
    /// </summary>
    internal Action<string, string>? DirectoryMoveHook { get; set; }

    /// <summary>Returns the verified backend root directory, extracting or self-healing it as needed. progress reports 0..1 over raw bytes written during extraction.</summary>
    public string EnsureExtracted(IProgress<double>? progress = null)
    {
        if (_verifiedDir is not null)
            return _verifiedDir;

        PayloadManifest manifest = _loadManifest();
        string hashDir = manifest.Hash[..HashDirLength];
        string target = Path.Combine(_backendRoot, hashDir);

        Directory.CreateDirectory(_backendRoot);

        if (Directory.Exists(target))
        {
            bool markedIncomplete = File.Exists(Path.Combine(target, IncompleteMarkerName));
            if (!markedIncomplete && VerifyExisting(target, manifest))
            {
                _verifiedDir = target;
                return target;
            }

            // Self-heal: never trust a partial or corrupt directory.
            DeleteDirectory(target);
        }

        // Clean up any extraction left half-finished by a previous crashed run.
        foreach (string stale in Directory.EnumerateDirectories(_backendRoot, hashDir + ".tmp-*"))
            DeleteDirectory(stale);

        string tmp = Path.Combine(_backendRoot, hashDir + ".tmp-" + Environment.ProcessId);
        if (Directory.Exists(tmp))
            DeleteDirectory(tmp);
        // A failed extraction leaves tmp behind (still marked .incomplete) for the next run to clean.
        Extract(tmp, manifest, progress);
        RetryOnTransientFsLock(() => MoveDirectory(tmp, target));

        _verifiedDir = target;
        return target;
    }

    /// <summary>Full re-hash of every manifest entry under <paramref name="target"/>; false on any missing/length-mismatch/hash-mismatch.</summary>
    private bool VerifyExisting(string target, PayloadManifest manifest)
    {
        ManifestVerifyPasses++;
        foreach (PayloadManifestEntry entry in manifest.Files)
        {
            string path = Path.Combine(target, entry.Path);
            if (!File.Exists(path))
                return false;
            using FileStream stream = File.OpenRead(path);
            if (stream.Length != entry.Length)
                return false;
            if (!Convert.ToHexString(SHA256.HashData(stream)).ToLowerInvariant().Equals(entry.Sha256, StringComparison.Ordinal))
                return false;
        }
        return true;
    }

    /// <summary>tmp→final rename through the <see cref="DirectoryMoveHook"/> test seam (production: <see cref="Directory.Move"/>).</summary>
    private void MoveDirectory(string source, string dest)
    {
        if (DirectoryMoveHook is { } move)
            move(source, dest);
        else
            Directory.Move(source, dest);
    }

    /// <summary>
    /// Runs <paramref name="action"/> retrying transient filesystem locks: IOException /
    /// UnauthorizedAccessException are retried up to <see cref="FsLockRetryAttempts"/>
    /// attempts spaced <see cref="FsLockRetryBackoffMs"/> ms apart; the final failure rethrows.
    /// </summary>
    private static void RetryOnTransientFsLock(Action action)
    {
        for (int attempt = 1; ; attempt++)
        {
            try
            {
                action();
                return;
            }
            catch (Exception e) when (e is IOException or UnauthorizedAccessException && attempt < FsLockRetryAttempts)
            {
                Thread.Sleep(FsLockRetryBackoffMs);
            }
        }
    }

    /// <summary>Extracts the whole payload into <paramref name="tmp"/>, verifying SHA-256 while writing. Throws on any mismatch (corrupt embedded payload).</summary>
    private void Extract(string tmp, PayloadManifest manifest, IProgress<double>? progress)
    {
        Directory.CreateDirectory(tmp);
        File.WriteAllText(Path.Combine(tmp, IncompleteMarkerName), "");

        long totalBytes = manifest.Files.Sum(f => f.Length);
        long written = 0;

        using Stream payload = _openPayload();
        List<PayloadArchiveEntry> index = PayloadPacker.ReadArchiveIndex(payload);
        if (index.Count != manifest.Files.Count)
            throw new InvalidDataException($"payload.bin 与 manifest 文件数不一致: {index.Count} vs {manifest.Files.Count}");

        for (int i = 0; i < index.Count; i++)
        {
            PayloadArchiveEntry entry = index[i];
            PayloadManifestEntry expected = manifest.Files[i];
            if (!string.Equals(entry.Path, expected.Path, StringComparison.Ordinal))
                throw new InvalidDataException($"payload.bin 与 manifest 顺序不一致: {entry.Path} vs {expected.Path}");

            string dest = SafeDestination(tmp, entry.Path);
            Directory.CreateDirectory(Path.GetDirectoryName(dest)!);

            long entryBytes = 0;
            using (Stream body = PayloadPacker.OpenArchiveBody(payload, entry.CompressedLength))
            using (SHA256 sha = SHA256.Create())
            {
                using (FileStream file = File.Create(dest))
                using (var hashed = new CryptoStream(file, sha, CryptoStreamMode.Write))
                {
                    byte[] buffer = new byte[64 * 1024];
                    int read;
                    while ((read = body.Read(buffer, 0, buffer.Length)) > 0)
                    {
                        hashed.Write(buffer, 0, read);
                        entryBytes += read;
                        written += read;
                        progress?.Report(totalBytes > 0 ? Math.Min(1.0, (double)written / totalBytes) : 1.0);
                    }
                }

                string hash = Convert.ToHexString(sha.Hash!).ToLowerInvariant();
                if (entryBytes != entry.RawLength || entryBytes != expected.Length ||
                    !hash.Equals(expected.Sha256, StringComparison.Ordinal))
                    throw new InvalidDataException($"嵌入载荷校验失败: {entry.Path}");
            }
        }

        File.Delete(Path.Combine(tmp, IncompleteMarkerName));
    }

    /// <summary>Resolves a payload-relative path under <paramref name="root"/>, rejecting anything that would escape the extraction root.</summary>
    private static string SafeDestination(string root, string relative)
    {
        if (string.IsNullOrEmpty(relative) || relative.Contains('\0') || relative.Contains(':'))
            throw new InvalidDataException($"载荷路径非法: {relative}");
        string dest = Path.GetFullPath(Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar)));
        string rootFull = Path.GetFullPath(root);
        if (!dest.StartsWith(rootFull + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidDataException($"载荷路径越界: {relative}");
        return dest;
    }

    /// <summary>Recursive delete that survives read-only attributes (license files in resources/ may carry them) and transient AV/indexer locks.</summary>
    private static void DeleteDirectory(string path)
    {
        try
        {
            RetryOnTransientFsLock(() => Directory.Delete(path, recursive: true));
        }
        catch (UnauthorizedAccessException)
        {
            foreach (string file in Directory.EnumerateFiles(path, "*", SearchOption.AllDirectories))
                File.SetAttributes(file, FileAttributes.Normal);
            RetryOnTransientFsLock(() => Directory.Delete(path, recursive: true));
        }
    }
}
